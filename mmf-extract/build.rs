//! Build the Lean extraction core, then generate the Rust side of its C ABI.
//!
//! The extractor's decoders live in `lean/` (a Lake project); this script runs
//! its build script, which produces `lean/build/libmmfextract.so`, and reads
//! that library's exported symbols. The mangled module initializer carries the
//! Lake package name in it, so its spelling is **discovered** rather than
//! assumed, and the resulting declarations are written to `$OUT_DIR` for
//! `src/lean.rs` to include.

use std::path::{Path, PathBuf};
use std::process::Command;

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let lean_dir = manifest.join("lean");

    // Re-run when the Lean sources, the package, or the build script change.
    for path in ["lean-toolchain", "lakefile.lean", "src", "build/build.sh", "lake-manifest.json"] {
        println!("cargo:rerun-if-changed={}", lean_dir.join(path).display());
    }

    let script = lean_dir.join("build").join("build.sh");
    let status = Command::new("sh")
        .arg(&script)
        .current_dir(&lean_dir)
        .env("LEAN_PATH", lean_dir.join(".lake/build/lib/lean"))
        .status()
        .unwrap_or_else(|e| panic!("could not run {}: {e}", script.display()));
    if !status.success() {
        panic!("the Lean extraction core failed to build (see the output above)");
    }

    let so_dir = lean_dir.join("build");
    let lib = so_dir.join("libmmfextract.so");
    if !lib.exists() {
        panic!("{} was not produced", lib.display());
    }
    let libdir = lean_lib_dir();

    // The symbols the Rust side calls. `ffi_extract` is the entry point and the
    // initializer carries the Lake package name, so both are read out of the
    // library rather than spelled by hand.
    let symbols = exported_symbols(&lib);
    let initializer = symbols
        .iter()
        .find(|s| s.ends_with("_MmfExtract_FFI") && s.starts_with("initialize_"))
        .unwrap_or_else(|| panic!("no `initialize_*MmfExtract_FFI` symbol in {}", lib.display()));
    if !symbols.iter().any(|s| *s == "mmf_extract") {
        panic!("no `mmf_extract` symbol in {}", lib.display());
    }

    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    let bindings = out.join("lean_core.rs");
    std::fs::write(
        &bindings,
        format!(
            r#"// Generated by build.rs from {lib}: do not edit.
// The Lean extraction core's C ABI, as the built library exports it.

// `mmf_extract` and the initializer come from the Lean core itself.
#[link(name = "mmfextract")]
unsafe extern "C" {{
    pub fn mmf_extract(request: *mut core::ffi::c_void) -> *mut core::ffi::c_void;
    pub fn {initializer}(builtin: u8) -> *mut core::ffi::c_void;
}}

// The initializer's name is mangled with the Lake package name
// (`mmf-extract-lean` becomes `mmf_x2dextract_x2dlean`), so the wrapper keeps
// the Rust side spelled the way the source reads.
pub unsafe fn initialize_lean_core() -> *mut core::ffi::c_void {{
    unsafe {{ {initializer}(1) }}
}}

// These come from the Lean runtime, `libleanshared.so`.
#[link(name = "leanshared")]
unsafe extern "C" {{
    pub fn lean_mk_string(text: *const core::ffi::c_char) -> *mut core::ffi::c_void;
    pub fn lean_initialize_runtime_module();
    pub fn lean_io_result_is_error(result: *mut core::ffi::c_void) -> bool;
    pub fn lean_io_result_show_error(result: *mut core::ffi::c_void);
}}
"#,
            lib = lib.display(),
            initializer = initializer,
        ),
    )
    .expect("writing the generated bindings");

    // Where the shared library and the Lean runtime it needs are found.
    println!("cargo:rustc-link-search=native={}", so_dir.display());
    println!("cargo:rustc-link-search=native={}", libdir.display());
    println!("cargo:rustc-link-lib=dylib=mmfextract");
    println!("cargo:rustc-link-lib=dylib=leanshared");
    for dir in [so_dir, libdir] {
        println!("cargo:rustc-link-arg=-Wl,-rpath,{}", dir.display());
    }
}

/// The Lean toolchain's `lib/lean` directory, which holds `libleanshared.so`.
fn lean_lib_dir() -> PathBuf {
    let out = Command::new("lean")
        .arg("--print-libdir")
        .output()
        .expect("running `lean --print-libdir`");
    assert!(out.status.success(), "`lean --print-libdir` failed");
    let text = String::from_utf8(out.stdout).expect("the lib dir is UTF-8");
    PathBuf::from(text.trim())
}

/// The dynamic symbol table of `lib`, as text.
fn exported_symbols(lib: &Path) -> Vec<String> {
    let out = Command::new("nm")
        .arg("-D")
        .arg("--defined-only")
        .arg(lib)
        .output()
        .unwrap_or_else(|e| panic!("running `nm -D {}`: {e}", lib.display()));
    assert!(out.status.success(), "`nm -D {}` failed", lib.display());
    String::from_utf8_lossy(&out.stdout)
        .lines()
        .filter_map(|row| {
            // "<address> T <name>" for a text symbol.
            let mut fields = row.split_whitespace();
            let _address = fields.next()?;
            let kind = fields.next()?;
            let name = fields.next()?;
            (kind == "T" || kind == "t").then(|| name.to_string())
        })
        .collect()
}
